# Writes the static, read-only copy of the living spec into docs\spec\ (readable from the repository, e.g. once it is on
# GitHub: open docs\spec\index.html in a browser). Same source as the artifact: build.ps1's page, then
#   - window.FLV_STATIC_COPY = true + the owner's ui/spec (docs\UI_SPEC.json) as window.FLV_SPEC_SNAPSHOT: the page's
#     runtime check (part3b_editor.js RUNTIME / resolveMode) then stays read-only, reads and writes no store and no
#     browser storage, and shows the owner's current values;
#   - a doctype + viewport (the artifact viewer adds its own skeleton), a banner naming it a static copy;
#   - no network: the Google Fonts link is dropped (the page's font stacks fall back to Agency FB / Arial Narrow);
#   - the images the page shows (img\*.png, img\*.jpg, img\cap\*) as WebP (captures at most 1280 px wide), the page's
#     .jpg references rewritten to .webp; img\screens\ (no longer drawn on the page) is left out.
#   tools\uimock\export.ps1          export (needs the images in research\evidence\controller_ui\mockup\img)
#   tools\uimock\export.ps1 -Check   exit 1 when docs\spec\index.html differs from a fresh export of the parts (or the
#                                    image names differ from the source images, when those exist); used by drift_check
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$root = Split-Path (Split-Path $here -Parent) -Parent
$dest = Join-Path $root 'docs\spec'
$srcImg = Join-Path $root 'research\evidence\controller_ui\mockup\img'
$py = Join-Path $root 'research\tools\ocr\.venv\Scripts\python.exe'
$utf8 = [Text.UTF8Encoding]::new($false)

# the page, exactly as build.ps1 concatenates it (built into a temp folder: the syntax check runs as well)
$tmp = Join-Path ([IO.Path]::GetTempPath()) ('flvibed_spec_export_' + [guid]::NewGuid().ToString('N'))
try {
    & (Join-Path $here 'build.ps1') -Out $tmp | Out-Null
    $html = [IO.File]::ReadAllText((Join-Path $tmp 'index.html'), $utf8)
} finally { Remove-Item $tmp -Recurse -Force -ErrorAction SilentlyContinue }

function Replace-Once([string]$s, [string]$old, [string]$new, [string]$what) {
    $i = $s.IndexOf($old); if ($i -lt 0 -or $s.IndexOf($old, $i + 1) -ge 0) { throw "export: expected exactly one $what in the page" }
    $s.Substring(0, $i) + $new + $s.Substring($i + $old.Length)
}
$html = [regex]::Replace($html, '<link rel="stylesheet" href="https://fonts\.googleapis\.com/[^"]*">\r?\n?', '')
$html = Replace-Once $html "const CAP = n => 'img/cap/' + n + '.jpg';" "const CAP = n => 'img/cap/' + n + '.webp';" 'CAP image helper'
$html = [regex]::Replace($html, '(img/[A-Za-z0-9_./\-]+?)\.jpg', '$1.webp')
if ($html -match 'https?://(?!claude\.ai)[^\s''"<>)]+\.(css|js|woff2?)\b') { throw "export: the page loads an external file ($($Matches[0])); inline it or drop it here" }
$snap = [IO.File]::ReadAllText((Join-Path $root 'docs\UI_SPEC.json'), $utf8).Trim() -replace '</', '<\/'   # JSON = a JS literal
$null = $snap | ConvertFrom-Json   # fails the export on a broken UI_SPEC.json
$banner = '<div class="staticnote" role="note">Static read-only copy of the living spec; the live page is on claude.ai (opens for people the owner shared it with).</div>'
$style = '<style>.staticnote { font-size: 13px; color: var(--fg-dim); background: var(--bg-2); border-bottom: 1px solid var(--line); padding: 5px 16px; text-align: center; }</style>'
$head = "<!doctype html>`n<html lang=""en"">`n<meta name=""viewport"" content=""width=device-width, initial-scale=1"">`n" +
        "<!-- Generated by tools\uimock\export.ps1 from tools\uimock\part*.* and docs\UI_SPEC.json; do not edit. -->`n" +
        "<script>window.FLV_STATIC_COPY = true; window.FLV_SPEC_SNAPSHOT = $snap;</script>`n"
$html = $head + (Replace-Once $html '<div class="toolbar">' "$style`n$banner`n<div class=""toolbar"">" 'toolbar')

$index = Join-Path $dest 'index.html'
$want = @()
if (Test-Path $srcImg) {
    $want = @(Get-ChildItem $srcImg -File | ForEach-Object { "img/$([IO.Path]::ChangeExtension($_.Name, $(if ($_.Extension -eq '.jpg') { '.webp' } else { $_.Extension })))" }) +
            @(Get-ChildItem (Join-Path $srcImg 'cap') -File -Filter *.jpg | ForEach-Object { "img/cap/$($_.BaseName).webp" })
}
if ($Check) {
    $bad = @()
    if (-not (Test-Path $index)) { $bad += 'docs\spec\index.html missing' }
    elseif (([IO.File]::ReadAllText($index, $utf8) -replace "`r`n", "`n") -ne ($html -replace "`r`n", "`n")) { # (a checkout may change line ends)
        $bad += 'docs\spec\index.html differs from the parts (run tools\uimock\export.ps1)' }
    if ($want) {
        $have = @(Get-ChildItem (Join-Path $dest 'img') -File -Recurse -ErrorAction SilentlyContinue | ForEach-Object { 'img/' + $_.FullName.Substring((Join-Path $dest 'img').Length + 1).Replace('\', '/') })
        $diff = @(Compare-Object ($want | Sort-Object) ($have | Sort-Object) | ForEach-Object { $_.InputObject })
        if ($diff) { $bad += "docs\spec images differ from the source: $(($diff | Select-Object -First 4) -join ', ')" }
        $newer = @(Get-ChildItem $srcImg -File -Recurse | Where-Object { $_.FullName -notmatch '\\screens\\' -and $_.LastWriteTime -gt (Get-Item $index -ErrorAction SilentlyContinue).LastWriteTime })
        if ($newer -and (Test-Path $index)) { $bad += "$($newer.Count) source image(s) newer than docs\spec (e.g. $($newer[0].Name))" }
    }
    if ($bad) { $bad | ForEach-Object { "spec copy: $_" }; exit 1 }
    "spec copy current (docs\spec\index.html, $($want.Count) images checked)"; exit 0
}

if (-not (Test-Path $srcImg)) { throw "export: the images are missing ($srcImg): run spec_images.py / assets.py first (tools\uimock\README.md)" }
New-Item -ItemType Directory -Force (Join-Path $dest 'img\cap') | Out-Null
$conv = @'
import os, sys
from PIL import Image
src, dst = sys.argv[1], sys.argv[2]
keep = set()
for sub, maxw in (("", 0), ("cap", 1280)):
    for n in sorted(os.listdir(os.path.join(src, sub))):
        p = os.path.join(src, sub, n)
        if not os.path.isfile(p) or not n.lower().endswith((".jpg", ".png")) or (sub == "cap" and not n.lower().endswith(".jpg")):
            continue
        out = os.path.join(dst, sub, n[:-4] + ".webp") if n.lower().endswith(".jpg") else os.path.join(dst, sub, n)
        keep.add(os.path.normcase(os.path.abspath(out)))
        if os.path.exists(out) and os.path.getmtime(out) >= os.path.getmtime(p):
            continue
        if n.lower().endswith(".png"):
            with open(p, "rb") as f, open(out, "wb") as g: g.write(f.read())
            continue
        im = Image.open(p).convert("RGB")
        if maxw and im.width > maxw:
            im = im.resize((maxw, round(im.height * maxw / im.width)), Image.LANCZOS)
        im.save(out, "WEBP", quality=72, method=6)
for d, _, fs in os.walk(dst):
    for n in fs:
        q = os.path.normcase(os.path.abspath(os.path.join(d, n)))
        if q not in keep: os.remove(q)
print(len(keep))
'@
$pyFile = Join-Path ([IO.Path]::GetTempPath()) 'flvibed_spec_img.py'
[IO.File]::WriteAllText($pyFile, $conv, $utf8)
try { $n = & $py -I $pyFile $srcImg (Join-Path $dest 'img'); if ($LASTEXITCODE -ne 0) { throw 'export: image conversion failed' } }
finally { Remove-Item $pyFile -ErrorAction SilentlyContinue }
[IO.File]::WriteAllText($index, $html, $utf8)
$size = (Get-ChildItem $dest -File -Recurse | Measure-Object Length -Sum).Sum
"exported $index ($([IO.File]::ReadAllBytes($index).Length) bytes) + $n images; docs\spec = $([math]::Round($size / 1MB, 1)) MB"
