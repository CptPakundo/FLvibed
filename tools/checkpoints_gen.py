"""Generates controller\\src\\impl\\checkpoints_gen.h from docs\\checkpoints.tsv (the story's hand-curated checkpoints,
docs\\TESTING.md "Speedrun splits"): the in-game split detector (controller\\src\\impl\\livesplit.cpp) reaches the same
checkpoints by the same conditions splits.py matches in the logs - `ours`: obj:<id> (the objective first shown),
control / land / launch / cutscene (mode changes), kill:<n> (the n-th destroyed marked solar), success (the mission's
result) - from the live game state, so one list drives the offline tables, the LiveSplit files and the in-game splits.

Usage (the OCR venv python, -I):  tools\\checkpoints_gen.py            write the header
                                  tools\\checkpoints_gen.py --check    exit 1 when the header is stale (drift check)
"""
import csv
import os
import sys

FL = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(FL, 'docs', 'checkpoints.tsv')
OUT = os.path.join(FL, 'controller', 'src', 'impl', 'checkpoints_gen.h')
KINDS = {'obj': 'Obj', 'control': 'Control', 'land': 'Land', 'launch': 'Launch', 'cutscene': 'Cutscene',
         'success': 'Success', 'kill': 'Kill'}


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def generate():
    rows = list(csv.DictReader(open(SRC, encoding='utf-8'), delimiter='\t'))
    out = ['// GENERATED by tools\\checkpoints_gen.py from docs\\checkpoints.tsv - do not edit; regenerate after a checkpoint',
           '// change (drift_check: --check). The story\'s checkpoints in order (14 legs, one row per checkpoint) with the',
           '// condition the in-game split detector (livesplit.cpp) and splits.py share (docs\\TESTING.md "Speedrun splits").',
           '#pragma once', '#include "common.h"', '', 'namespace checkpoints', '{',
           'enum Kind : u8', '{',
           '    Obj,      // the objective with text id `value` is shown (pub::Player::SetMissionObjectives entry 0)',
           '    Control,  // the HUD back in space: mode cutscene / docked -> space (after a launch or a space scene)',
           '    Land,     // mode -> docked (from a game mode, not from the menu)',
           '    Launch,   // mode docked -> a space mode',
           '    Cutscene, // mode space -> cutscene (a story scene in space)',
           '    Success,  // the mission\'s result: the objective list cleared (SetMissionObjectives count 0)',
           '    Kill,     // the `value`-th destroyed solar the mission marked (counted per leg)',
           '};', 'struct Row', '{',
           '    const char* leg;     // "M01a"',
           '    const char* cp;      // "M01a.wing" (the LiveSplit segment name is the part after the dot)',
           '    Kind kind;',
           '    u32 value;           // Obj: the text id; Kill: n; else 0',
           '    const char* segment; // what happens in the segment this checkpoint ends',
           '};', 'constexpr Row kRows[] = {']
    for r in rows:
        kind, _, val = r['ours'].strip().partition(':')
        if kind not in KINDS:
            raise SystemExit(f'{r["cp"]}: unknown ours kind {r["ours"]!r}')
        out.append(f'    {{{cstr(r["leg"])}, {cstr(r["cp"])}, {KINDS[kind]}, {int(val) if val else 0}u, '
                   f'{cstr(r["segment"])}}},')
    out += ['};', f'constexpr int kCount = {len(rows)};', '} // namespace checkpoints', '']
    return '\n'.join(out)


def main():
    text = generate()
    if '--check' in sys.argv:
        cur = open(OUT, encoding='utf-8').read() if os.path.isfile(OUT) else ''
        if cur != text:
            print(f'STALE: {OUT} differs from {SRC} (run tools\\checkpoints_gen.py)')
            sys.exit(1)
        print('checkpoints_gen.h: current')
        return
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(f'{OUT}: {text.count(chr(10))} lines')


if __name__ == '__main__':
    main()
