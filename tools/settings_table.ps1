# The settings reference, generated from the code (core\settings.h registries): every row of the three modules' Def
# tables - name, type, range, default, help - into docs\SETTINGS.md, so the documentation of a setting lives once, in the
# row that declares it (checkup 24 Oct 2026; drift_check.ps1 "settings-doc" compares the file with a fresh generation).
# Defaults are read from the struct initialisers (`type field = value` in the module's headers / sources); a default the
# script cannot find is printed as `?` (fix the initialiser's form, not this script).
# Usage (PowerShell): tools\settings_table.ps1 [-Out <path>] [-Check]   -Check: exit 1 when docs\SETTINGS.md is stale
param([string]$Out = '', [switch]$Check)
$root = Split-Path $PSScriptRoot -Parent
if (-not $Out) { $Out = Join-Path $root 'docs\SETTINGS.md' }

# module -> (registry source, ini section, the files that hold the struct initialisers, the two hand-written word keys)
$modules = @(
    @{ Name = 'Controller'; Ini = 'EXE\FLController.ini [Controller]'; Source = 'controller\src\impl\controller.cpp'
       Defaults = @('controller\src\impl\controller.cpp', 'controller\src\impl\gamepad.h', 'controller\src\impl\shieldcue.h', 'controller\src\impl\shieldcue.cpp', 'controller\src\impl\reticlecue.h', 'controller\src\impl\reticlecue.cpp', 'controller\src\impl\uiopt.h')
       Extra = @() }
    @{ Name = 'Autopilot'; Ini = 'EXE\FLController.ini [Autopilot]'; Source = 'controller\src\impl\autopilot_settings.cpp'
       Defaults = @('controller\src\impl\autopilot_impl.h')
       Extra = @(
           @{ name = 'consumables'; type = 'word'; range = 'needed | never'; default = 'needed'; help = 'sets missiles, repair and countermeasures together (user, 18 Oct 2026)' },
           @{ name = 'p.<field>'; type = 'string'; range = '-'; default = '-'; help = 'a personality field of the [Pilot] by its ini name (e.g. p.trail_distance = 200)' }) }
    @{ Name = 'Subtitles'; Ini = 'EXE\FLSubtitles.ini [Subtitles]'; Source = 'subtitles\src\impl\display.cpp'
       Defaults = @('subtitles\src\impl\display.h')
       Extra = @() }
)
$typeNames = @{ Bool = 'bool'; Int = 'int'; Float = 'float'; Hex = 'id'; String = 'string'; Vec3 = 'x, y, z' }
$row = [regex]'\{"(?<name>[a-z_0-9]+)",\s*(?:settings::)?(?<type>Bool|Int|Float|Hex|String|Vec3),\s*&(?<ptr>[^,]+),\s*(?<min>[-0-9.ef]+|kNoMax),\s*(?<max>[-0-9.ef]+|kNoMax),\s*(?<help>(?:"(?:[^"\\]|\\.)*"\s*)+)\}'

function Default($field, [string[]]$files) {
    foreach ($f in $files) {
        $t = Get-Content (Join-Path $root $f) -Raw
        foreach ($m in [regex]::Matches($t, "(?m)(?:^|[\s,;{])$([regex]::Escape($field))(?:\[\d\])?\s*=\s*(?<v>\{[^}]*\}|[^,;/]+)")) {
            # not inside a string literal or a comment on its line (a log format "self hull=%.3f ..." in controller.cpp
            # was once read as hull_cue's default)
            $ls = $t.LastIndexOf("`n", [Math]::Max(0, $m.Index)) + 1
            $pre = $t.Substring($ls, $m.Index - $ls + 1) -replace '\\.', ''
            if ($pre.Contains('//') -or (($pre.ToCharArray() | Where-Object { $_ -eq '"' }).Count % 2) -eq 1) { continue }
            return $m.Groups['v'].Value.Trim() -replace '\{|\}', '' -replace '\s+', ' ' -replace '(\d)f\b', '$1' -replace '^"(.*)"$', '$1'
        }
    }
    return '?'
}
function Range($min, $max, $type) {
    if ($type -eq 'Bool') { return '0 \| 1' }  # (escaped: a bare pipe split the table row)
    if ($min -eq '0' -and $max -eq '0') { return '-' }
    $hi = if ($max -eq 'kNoMax') { 'no cap' } else { $max }
    return "$min .. $hi"
}

$sb = New-Object Text.StringBuilder
$null = $sb.AppendLine('# FLvibed settings reference')
$null = $sb.AppendLine('')
$null = $sb.AppendLine('**Generated by `tools\settings_table.ps1` from the code (`core\settings.h` registries) - do not edit; edit the row''s help')
$null = $sb.AppendLine('in the source and regenerate.** `set <name> <value>` / `ap set` change a value live; `config save` writes the ini with these')
$null = $sb.AppendLine('help lines; `config settings` / `ap settings` / `settings` list them in the game. Behaviour, measurements and the why of')
$null = $sb.AppendLine('each default: `controller\docs\AUTOPILOT.md`, `subtitles\docs\DISPLAY_PLAN.md`, `controller\docs\HUD_CUES.md`.')
$total = 0
foreach ($m in $modules) {
    $src = Get-Content (Join-Path $root $m.Source) -Raw
    $rows = @()
    foreach ($x in $row.Matches($src)) {
        # adjacent literals joined as the compiler joins them: only the outer quotes (and the whitespace outside them)
        # go; a space inside a literal stays (a Trim per piece once ate "keyboard " + "and mouse" to "keyboardand")
        $help = (($x.Groups['help'].Value -split '"\s*"' | ForEach-Object { $_ -replace '^\s*"', '' -replace '"\s*$', '' }) -join '') -replace '\\\\', '\' -replace '\\"', '"'
        $field = ($x.Groups['ptr'].Value -split '\.|->')[-1].Trim()
        $rows += [pscustomobject]@{ name = $x.Groups['name'].Value; type = $typeNames[$x.Groups['type'].Value]
                                     range = Range $x.Groups['min'].Value $x.Groups['max'].Value $x.Groups['type'].Value
                                     default = Default $field $m.Defaults; help = $help }
    }
    foreach ($e in $m.Extra) { $rows += [pscustomobject]$e }
    $total += $rows.Count
    $null = $sb.AppendLine('')
    $null = $sb.AppendLine("## [$($m.Name)] - $($m.Ini) ($($rows.Count) keys; source ``$($m.Source)``)")
    $null = $sb.AppendLine('')
    $null = $sb.AppendLine('| Setting | Type | Range | Default | What it does |')
    $null = $sb.AppendLine('|---|---|---|---|---|')
    foreach ($r in $rows) {
        $h = $r.help -replace '\|', '\|'
        $null = $sb.AppendLine("| ``$($r.name)`` | $($r.type) | $($r.range) | $($r.default) | $h |")
    }
}
$text = $sb.ToString().Replace("`r`n", "`n")
if ($Check) {
    $old = if (Test-Path $Out) { (Get-Content $Out -Raw).Replace("`r`n", "`n") } else { '' }
    if ($old -eq $text) { "settings doc current ($total keys)"; exit 0 }
    "settings doc STALE: regenerate with tools\settings_table.ps1 ($total keys)"; exit 1
}
[IO.File]::WriteAllText($Out, $text, (New-Object Text.UTF8Encoding $false))
"wrote $Out ($total keys)"
